def context_pack_command(args: argparse.Namespace) -> None:
    root = Path(args.repo).expanduser().resolve(strict=True)
    session_dir, session, manifest = load_session(root, args.session, args.state_dir)
    max_bytes = min(max(args.max_bytes, 1), MAX_CONTEXT_PACK)
    result = {
        "session_id": session["session_id"],
        "claims": [],
        "valid_claims": 0,
        "invalidated_claims": 0,
        "omitted_by_policy": 0,
        "omitted_by_budget": 0,
    }
    hash_cache: dict[str, str | None] = {}
    eligible = {
        item["path"] for item in manifest["inventory"]["entries"]
        if item["text_candidate"] and item["excluded_reason"] is None
    }
    for record in evidence_records(session_dir / "evidence.jsonl"):
        classification = record.get("classification")
        if classification not in CLASSIFICATIONS or classification == "unverified_hypothesis":
            result["omitted_by_policy"] += 1
            continue
        if classification == "historical_fact" and not args.include_historical:
            result["omitted_by_policy"] += 1
            continue
        if not evidence_is_current(root, manifest, record, hash_cache, eligible):
            result["invalidated_claims"] += 1
            continue
        result["valid_claims"] += 1
        claim = {
            "id": record.get("id"),
            "claim": redact_text(str(record.get("claim", ""))),
            "classification": classification,
            "scope": redact_text(str(record.get("scope", ""))),
            "sources": record.get("sources", []),
            "notes": redact_text(str(record.get("notes", ""))),
        }
        result["claims"].append(claim)
        if len(json_text(result).encode("utf-8")) > max_bytes:
            result["claims"].pop()
            result["omitted_by_budget"] += 1
    emit(result, max_bytes)


def add_common(parser: argparse.ArgumentParser, session_required: bool = True) -> None:
    parser.add_argument("--repo", required=True, help="Exact target repository root.")
    parser.add_argument("--state-dir", help="Optional cache directory outside the target repository.")
    parser.add_argument(
        "--session", required=session_required,
        help="Session ID returned by inventory; optional for resume."
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Bounded, read-only repository inspection and resumable evidence sessions."
    )
    commands = parser.add_subparsers(dest="command", required=True)

    inventory = commands.add_parser("inventory", help="Create a metadata-only inventory and new session.")
    add_common(inventory, session_required=False)
    inventory.add_argument("--max-entries", type=int, default=MAX_INVENTORY_ENTRIES)

    search = commands.add_parser("search", help="Search source files with bounded output.")
    add_common(search)
    search.add_argument("--pattern", required=True)
    search.add_argument("--glob", help="Optional repository-relative file glob.")
    search.add_argument("--regex", action="store_true", help="Treat pattern as a regular expression.")
    search.add_argument("--case-sensitive", action="store_true")
    search.add_argument("--offset", type=int, default=0, help="0-based file index in the matching manifest.")
    search.add_argument("--line-offset", type=int, default=0, help="0-based line index within the current file; pair with --offset.")
    search.add_argument("--max-files", type=int, default=MAX_SEARCH_FILES)
    search.add_argument("--max-matches", type=int, default=MAX_SEARCH_MATCHES)
    search.add_argument("--max-bytes", type=int, default=MAX_SEARCH_BYTES)
    search.add_argument("--before", type=int, default=2)
    search.add_argument("--after", type=int, default=2)

    read = commands.add_parser("read", help="Read one file or a narrow line range.")
    add_common(read)
    read.add_argument("--path", required=True)
    read.add_argument("--start-line", type=int)
    read.add_argument("--end-line", type=int)
    read.add_argument("--max-bytes", type=int, default=MAX_READ_OUTPUT)

    count = commands.add_parser("count", help="Run or resume a bounded raw-text count job.")
    add_common(count)
    count.add_argument("--pattern", required=True)
    count.add_argument("--glob", help="Optional repository-relative file glob (backslashes accepted).")
    count.add_argument("--regex", action="store_true")
    count.add_argument("--case-sensitive", action="store_true")
    count.add_argument("--restart", action="store_true", help="Restart this count job from the beginning.")
    count.add_argument("--max-files", type=int, default=MAX_COUNT_FILES)
    count.add_argument("--max-bytes", type=int, default=MAX_COUNT_BYTES)

    evidence = commands.add_parser("evidence", help="Persist compact source-backed claims.")
    evidence_commands = evidence.add_subparsers(dest="evidence_command", required=True)
    evidence_add = evidence_commands.add_parser("add", help="Add one evidence record.")
    add_common(evidence_add)
    evidence_add.add_argument("--claim", required=True)
    evidence_add.add_argument("--classification", choices=sorted(CLASSIFICATIONS), required=True)
    evidence_add.add_argument("--path", required=True)
    evidence_add.add_argument("--symbol")
    evidence_add.add_argument("--start-line", type=int)
    evidence_add.add_argument("--end-line", type=int)
    evidence_add.add_argument("--scope")
    evidence_add.add_argument("--notes")

    checkpoint = commands.add_parser("checkpoint", help="Save the current phase and next logical task.")
    add_common(checkpoint)
    checkpoint.add_argument("--phase", choices=sorted(PHASES), required=True)
    checkpoint.add_argument("--completed-task")
    checkpoint.add_argument("--next-task")

    resume = commands.add_parser("resume", help="Show the latest or specified session checkpoint.")
    add_common(resume, session_required=False)

    pack = commands.add_parser("context-pack", help="Return only source-validated claims within a hard byte budget.")
    add_common(pack)
    pack.add_argument("--max-bytes", type=int, default=MAX_CONTEXT_PACK)
    pack.add_argument("--include-historical", action="store_true")

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        if args.command == "inventory":
            inventory_command(args)
        elif args.command == "search":
            search_command(args)
        elif args.command == "read":
            read_command(args)
        elif args.command == "count":
            count_command(args)
        elif args.command == "evidence" and args.evidence_command == "add":
            evidence_add_command(args)
        elif args.command == "checkpoint":
            checkpoint_command(args)
        elif args.command == "resume":
            resume_command(args)
        elif args.command == "context-pack":
            context_pack_command(args)
        else:
            parser.error("Unsupported command.")
        return 0
    except (OSError, ValueError, RuntimeError, KeyError, json.JSONDecodeError) as exc:
        print(json.dumps({"error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
