def redact_text(text: str) -> str:
    """Best-effort redaction; not a replacement for excluding secret files."""
    text = PRIVATE_KEY_BLOCK.sub("[REDACTED PRIVATE KEY]", text)
    text = SECRET_ASSIGNMENT.sub(lambda m: m.group("prefix") + "[REDACTED]", text)
    text = BEARER_TOKEN.sub("Bearer [REDACTED]", text)
    return SECRET_TOKEN.sub("[REDACTED]", text)


def normalize_relative_path(value: str) -> str:
    """Use platform-neutral slash-separated paths for manifest lookups."""
    normalized = value.replace("\\", "/")
    relative = PurePosixPath(normalized)
    if (
        not normalized or normalized.startswith("/")
        or not relative.parts or any(part == ".." for part in relative.parts)
        or ":" in relative.parts[0]
    ):
        raise ValueError("Path must be a repository-relative path without traversal.")
    return relative.as_posix()


def is_sensitive_file(rel: str, name: str) -> bool:
    lower = name.lower()
    path_parts = [part.lower() for part in PurePosixPath(rel).parts]
    if lower.startswith(".env") or lower in SENSITIVE_NAMES:
        return True
    if Path(lower).suffix in SENSITIVE_EXTENSIONS:
        return True
    if any(part in {".ssh", ".aws", ".kube", ".gnupg"} for part in path_parts[:-1]):
        return True
    return False
