def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def json_text(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True)


def emit(value: Any, limit: int | None = None) -> None:
    rendered = json_text(value)
    if limit is not None and len(rendered.encode("utf-8")) > limit:
        raise RuntimeError("Output exceeded the declared response budget.")
    print(rendered)


def emit_inventory_summary(summary: dict[str, Any]) -> None:
    """Always return the session ID, even for very wide repository inventories."""
    inventory = summary["inventory"]
    inventory["summary_truncated"] = False
    for _ in range(100):
        if len(json_text(summary).encode("utf-8")) <= MAX_INVENTORY_OUTPUT:
            emit(summary, MAX_INVENTORY_OUTPUT)
            return
        inventory["summary_truncated"] = True
        candidates = inventory["candidate_files"]
        top_level = inventory["top_level"]
        if len(candidates) > 1:
            del candidates[max(1, len(candidates) // 2):]
        elif len(top_level) > 1:
            del top_level[max(1, len(top_level) // 2):]
        elif len(inventory["by_extension"]) > 1:
            keys = list(inventory["by_extension"])
            for key in keys[len(keys) // 2:]:
                del inventory["by_extension"][key]
        elif len(inventory["excluded_counts"]) > 1:
            keys = list(inventory["excluded_counts"])
            for key in keys[len(keys) // 2:]:
                del inventory["excluded_counts"][key]
        else:
            break
    emit({
        "session_id": summary["session_id"],
        "repository": summary["repository"],
        "inventory": {
            "file_count": inventory["file_count"],
            "text_candidate_count": inventory["text_candidate_count"],
            "truncated": inventory["truncated"],
            "inventory_complete": inventory["inventory_complete"],
            "scan_error_count": len(inventory["scan_errors"]),
            "summary_truncated": True,
        },
        "reuse": summary["reuse"],
        "state_directory": summary["state_directory"],
    }, MAX_INVENTORY_OUTPUT)


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(json_text(value) + "\n", encoding="utf-8")
    temp.replace(path)


def append_jsonl(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n")


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def git_output(root: Path, *args: str, timeout: int = 5) -> str | None:
    try:
        result = subprocess.run(
            ["git", "-C", str(root), *args],
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if result.returncode != 0:
        return None
    return result.stdout.strip()


def git_metadata(root: Path) -> tuple[dict[str, Any], set[str]]:
    git_root = git_output(root, "rev-parse", "--show-toplevel")
    if not git_root:
        return {
            "is_repository": False,
            "head": None,
            "branch": None,
            "dirty": None,
        }, set()

    canonical_git_root = Path(git_root).resolve()
    if canonical_git_root != root:
        raise ValueError(
            "The supplied path is inside a Git worktree but is not its root. "
            "Pass the exact repository root; the helper will not widen scope."
        )

    head = git_output(root, "rev-parse", "HEAD")
    branch = git_output(root, "branch", "--show-current")
    status = git_output(root, "status", "--porcelain", "--untracked-files=no")
    tracked_raw = git_output(root, "ls-files", "-z")
    tracked = set(tracked_raw.split("\0")) if tracked_raw else set()
    tracked.discard("")
    return {
        "is_repository": True,
        "head": head,
        "branch": branch or None,
        "dirty": bool(status),
    }, tracked


def cache_root() -> Path:
    if os.name == "nt":
        base = os.environ.get("LOCALAPPDATA")
        return Path(base) / "agent-wiki" if base else Path.home() / "AppData" / "Local" / "agent-wiki"
    base = os.environ.get("XDG_CACHE_HOME")
    return Path(base) / "agent-wiki" if base else Path.home() / ".cache" / "agent-wiki"


def state_base(root: Path, explicit: str | None) -> Path:
    base = Path(explicit).expanduser() if explicit else cache_root()
    base = base.resolve()
    try:
        base.relative_to(root)
    except ValueError:
        return base
    raise ValueError("Session state must be stored outside the target repository.")


def repository_key(root: Path) -> str:
    normalized = os.path.normcase(str(root.resolve()))
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()[:16]


def is_generated(rel: str, name: str) -> bool:
    parts = [part.lower() for part in PurePosixPath(rel).parts]
    lower = name.lower()
    if any(part in GENERATED_DIRS for part in parts[:-1]):
        return True
    if lower.endswith((".gen.c", ".gen.h", ".gen.cpp", ".gen.hpp", ".pb.c", ".pb.h", ".pb.cc", ".pb.cpp")):
        return True
    if lower.endswith(("_generated.c", "_generated.h", "_generated.cpp", "_generated.hpp")):
        return True
    if ".generated." in lower or lower.startswith("moc_"):
        return True
    return False


def excluded_directory(rel: str, name: str, tracked: set[str], path: Path | None = None) -> str | None:
    if path is not None and (path / ".git").exists():
        return "nested repository or submodule (read-only boundary)"
    lower = name.lower()
    if lower in EXCLUDED_DIRS:
        return "generated/build/cache directory"
    if lower in GENERATED_DIRS:
        return "generated source directory"
    if lower in {"vendor", "third_party", "third-party", "external"}:
        return "third-party or external source tree"
    if lower == "dependency" and tracked:
        prefix = rel.rstrip("/") + "/"
        if not any(item.startswith(prefix) for item in tracked):
            return "untracked dependency output directory"
    return None


def excluded_file(rel: str, name: str) -> str | None:
    lower = name.lower()
    if lower == "build.sh":
        return "build.sh ignored by policy"
    if is_sensitive_file(rel, name):
        return "potentially sensitive configuration or key"
    if is_generated(rel, name):
        return "generated source"
    if Path(name).suffix.lower() in BINARY_EXTENSIONS:
        return "binary or generated artifact"
    return None


def is_text_candidate(name: str, reason: str | None) -> bool:
    if reason:
        return False
    suffix = Path(name).suffix.lower()
    if name.lower() in TEXT_NAMES:
        return True
    return bool(suffix) and suffix in TEXT_EXTENSIONS


def is_candidate_file(rel: str) -> bool:
    path = PurePosixPath(rel)
    name = path.name.lower()
    parts = [part.lower() for part in path.parts]
    if name in CANDIDATE_NAMES:
        return True
    if name.startswith(("license", "notice", "changelog", "change")):
        return True
    if ".github" in parts and "workflows" in parts:
        return True
    if parts and parts[0] in {"src", "include", "test", "tests", "tools", "samples", "config", "build"}:
        return len(parts) <= 2 and (path.suffix.lower() in TEXT_EXTENSIONS or name in CANDIDATE_NAMES)
    return False


def build_inventory(root: Path, git: dict[str, Any], tracked: set[str], max_entries: int) -> dict[str, Any]:
    entries: list[dict[str, Any]] = []
    by_extension: collections.Counter[str] = collections.Counter()
    excluded_counts: collections.Counter[str] = collections.Counter()
    candidate_files: list[str] = []
    top_level: list[str] = []
    try:
        top_level = sorted(
            entry.name for entry in os.scandir(root)
            if entry.name not in {".git", ".hg", ".svn"}
        )
    except OSError:
        pass

    truncated = False
    file_count = 0
    text_count = 0
    scan_errors: list[dict[str, str]] = []
    excluded_paths: list[dict[str, str]] = []

    def on_walk_error(error: OSError) -> None:
        if len(scan_errors) < 100:
            scan_errors.append({
                "path": str(Path(error.filename).relative_to(root)) if error.filename
                and Path(error.filename).is_relative_to(root) else str(error.filename or ""),
                "error": type(error).__name__,
            })

    for current, dirs, files in os.walk(
        root, topdown=True, followlinks=False, onerror=on_walk_error
    ):
        current_path = Path(current)
        rel_dir = current_path.relative_to(root).as_posix()
        kept_dirs: list[str] = []
        for dirname in sorted(dirs):
            dir_path = current_path / dirname
            rel = (PurePosixPath(rel_dir) / dirname).as_posix() if rel_dir != "." else dirname
            if dir_path.is_symlink():
                excluded_counts["symbolic link directory"] += 1
                continue
            reason = excluded_directory(rel, dirname, tracked, dir_path)
            if reason:
                excluded_counts[reason] += 1
                if len(excluded_paths) < 100:
                    excluded_paths.append({"path": rel, "reason": reason})
                continue
            kept_dirs.append(dirname)
        dirs[:] = kept_dirs

        for filename in sorted(files):
            path = current_path / filename
            rel = (PurePosixPath(rel_dir) / filename).as_posix() if rel_dir != "." else filename
            if path.is_symlink():
                excluded_counts["symbolic link file"] += 1
                continue
            try:
                stat_result = path.stat()
            except OSError as exc:
                excluded_counts["unreadable metadata"] += 1
                if len(scan_errors) < 100:
                    scan_errors.append({"path": rel, "error": type(exc).__name__})
                continue
            if not path.is_file():
                continue
            if len(entries) >= max_entries:
                truncated = True
                break
            file_count += 1
            extension = Path(filename).suffix.lower()
            by_extension[extension or "[no extension]"] += 1
            reason = excluded_file(rel, filename)
            text_candidate = is_text_candidate(filename, reason)
            if text_candidate:
                text_count += 1
            elif reason:
                excluded_counts[reason] += 1
            else:
                excluded_counts["not a supported text source"] += 1
                reason = "not a supported text source"

            if is_candidate_file(rel) and len(candidate_files) < 100:
                candidate_files.append(rel)

            entries.append({
                "path": rel,
                "size": stat_result.st_size,
                "mtime_ns": stat_result.st_mtime_ns,
                "extension": extension,
                "text_candidate": text_candidate,
                "excluded_reason": reason,
            })
        if truncated:
            break

    return {
        "file_count": file_count,
        "text_candidate_count": text_count,
        "by_extension": dict(sorted(by_extension.items())),
        "top_level": top_level,
        "candidate_files": candidate_files,
        "excluded_counts": dict(sorted(excluded_counts.items())),
        "truncated": truncated,
        "inventory_complete": not truncated and not scan_errors,
        "scan_errors": scan_errors,
        "excluded_paths": excluded_paths,
        "entries": entries,
    }


def hash_file(path: Path, max_bytes: int = MAX_COUNT_FILE_BYTES) -> str:
    if path.stat().st_size > max_bytes:
        raise ValueError("File is too large to fingerprint safely.")
    digest = hashlib.sha256()
    processed = 0
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            processed += len(chunk)
            if processed > max_bytes:
                raise ValueError("File changed or exceeded the fingerprint budget.")
            digest.update(chunk)
    return digest.hexdigest()


def session_parent(root: Path, explicit_state: str | None) -> Path:
    return state_base(root, explicit_state) / repository_key(root) / "sessions"


def latest_session_dir(parent: Path) -> Path | None:
    if not parent.is_dir():
        return None
    candidates = []
    for child in parent.iterdir():
        if child.is_dir() and (child / "session.json").is_file():
            candidates.append(child)
    return max(candidates, key=lambda item: item.stat().st_mtime_ns) if candidates else None


def safe_file(root: Path, rel_text: str) -> Path:
    normalized = normalize_relative_path(rel_text)
    relative = PurePosixPath(normalized)
    if is_sensitive_file(normalized, relative.name):
        raise ValueError("Potentially sensitive files are not inspected.")
    current = root
    for part in relative.parts:
        current = current / part
        if current.is_symlink():
            raise ValueError("Symbolic links are not followed by the helper.")
    resolved = current.resolve(strict=True)
    try:
        resolved.relative_to(root)
    except ValueError as exc:
        raise ValueError("Resolved path escapes the target repository.") from exc
    if not resolved.is_file():
        raise ValueError("Path is not a regular file.")
    if resolved.name.lower() == "build.sh":
        raise ValueError("build.sh is intentionally not inspected.")
    return resolved


def manifest_entries(manifest: dict[str, Any], glob_pattern: str | None = None) -> list[dict[str, Any]]:
    entries = [
        item for item in manifest["inventory"]["entries"]
        if item["text_candidate"] and item["excluded_reason"] is None
    ]
    if glob_pattern:
        normalized_glob = normalize_relative_path(glob_pattern)
        entries = [item for item in entries if fnmatch.fnmatch(item["path"], normalized_glob)]
    return entries


def evidence_records(path: Path) -> Iterable[dict[str, Any]]:
    """Stream records instead of loading a potentially large JSONL file."""
    if not path.is_file():
        return
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            try:
                item = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(item, dict):
                yield item


def evidence_is_current(
    root: Path, manifest: dict[str, Any], record: dict[str, Any],
    hash_cache: dict[str, str | None] | None = None,
    eligible: set[str] | None = None,
) -> bool:
    sources = record.get("sources") or []
    if not sources:
        return False
    if eligible is None:
        eligible = {
            item["path"] for item in manifest["inventory"]["entries"]
            if item["text_candidate"] and item["excluded_reason"] is None
        }
    if hash_cache is None:
        hash_cache = {}
    for source in sources:
        rel = source.get("path")
        expected = source.get("sha256")
        if not rel or not expected or rel not in eligible:
            return False
        if rel not in hash_cache:
            try:
                hash_cache[rel] = hash_file(safe_file(root, rel))
            except (OSError, ValueError):
                hash_cache[rel] = None
        if hash_cache[rel] != expected:
            return False
    return True


def reuse_previous_evidence(root: Path, manifest: dict[str, Any], previous_dir: Path | None, target: Path) -> tuple[int, int, str | None]:
    if not previous_dir:
        return 0, 0, None
    previous_session_path = previous_dir / "session.json"
    previous_evidence_path = previous_dir / "evidence.jsonl"
    if not previous_session_path.is_file():
        return 0, 0, None
    try:
        previous_session = read_json(previous_session_path)
    except (OSError, json.JSONDecodeError):
        return 0, 0, None
    reused = 0
    invalidated = 0
    hash_cache: dict[str, str | None] = {}
    eligible = {
        item["path"] for item in manifest["inventory"]["entries"]
        if item["text_candidate"] and item["excluded_reason"] is None
    }
    for record in evidence_records(previous_evidence_path):
        classification = record.get("classification")
        if classification == "unverified_hypothesis":
            continue
        if classification not in CLASSIFICATIONS:
            invalidated += 1  # Older schema claims need explicit reclassification.
            continue
        if evidence_is_current(root, manifest, record, hash_cache, eligible):
            for field in ("claim", "scope", "notes"):
                if isinstance(record.get(field), str):
                    record[field] = redact_text(record[field])
            for source in record.get("sources", []):
                if isinstance(source.get("symbol"), str):
                    source["symbol"] = redact_text(source["symbol"])
            record["reused_from_session_id"] = previous_session.get("session_id")
            append_jsonl(target, record)
            reused += 1
        else:
            invalidated += 1
    return reused, invalidated, previous_session.get("session_id")


def inventory_command(args: argparse.Namespace) -> dict[str, Any]:
    root = Path(args.repo).expanduser().resolve(strict=True)
    if not root.is_dir():
        raise ValueError("Repository path must be a directory.")
    git, tracked = git_metadata(root)
    key = repository_key(root)
    parent = session_parent(root, args.state_dir)
    previous_dir = latest_session_dir(parent)
    max_entries = min(max(args.max_entries, 1), MAX_INVENTORY_ENTRIES)
    inventory = build_inventory(root, git, tracked, max_entries)
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "repository": {"root": str(root), "key": key, "git": git},
        "created_at": now_iso(),
        "inventory": inventory,
    }

    session_id = uuid.uuid4().hex[:12]
    session_dir = parent / session_id
