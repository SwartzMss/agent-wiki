def load_session(root: Path, session_id: str | None, state_dir: str | None) -> tuple[Path, dict[str, Any], dict[str, Any]]:
    # Windows temporary paths can have different lexical representations
    # (8.3 names, junctions, or letter casing). Compare canonical paths.
    root = Path(root).expanduser().resolve(strict=True)
    parent = session_parent(root, state_dir)
    if session_id:
        if not re.fullmatch(r"[a-f0-9]{12}", session_id):
            raise ValueError("Invalid session ID.")
        session_dir = parent / session_id
    else:
        session_dir = latest_session_dir(parent)
        if session_dir is None:
            raise ValueError("No session exists for this repository. Run inventory first.")
    session_path = session_dir / "session.json"
    manifest_path = session_dir / "source-manifest.json"
    if not session_path.is_file() or not manifest_path.is_file():
        raise ValueError("Session is incomplete or its manifest is missing.")
    session = read_json(session_path)
    manifest = read_json(manifest_path)
    if Path(session["repository"]["root"]).resolve() != root:
        raise ValueError("Session repository root does not match the requested repository.")
    return session_dir, session, manifest


def save_session(session_dir: Path, session: dict[str, Any]) -> None:
    session["updated_at"] = now_iso()
    write_json(session_dir / "session.json", session)


def search_command(args: argparse.Namespace) -> None:
    root = Path(args.repo).expanduser().resolve(strict=True)
    session_dir, session, manifest = load_session(root, args.session, args.state_dir)
    flags = 0 if args.case_sensitive else re.IGNORECASE
    expression = args.pattern if args.regex else re.escape(args.pattern)
    try:
        matcher = re.compile(expression, flags)
    except re.error as exc:
        raise ValueError(f"Invalid search expression: {exc}") from exc

    entries = manifest_entries(manifest, args.glob)
    offset = max(args.offset, 0)
    line_offset = max(getattr(args, "line_offset", 0), 0)
    if offset > len(entries) or (offset == len(entries) and line_offset):
        raise ValueError("Search cursor is beyond the available file list.")
    max_files = min(max(args.max_files, 1), MAX_SEARCH_FILES)
    max_matches = min(max(args.max_matches, 1), MAX_SEARCH_MATCHES)
    max_bytes = min(max(args.max_bytes, 1), MAX_SEARCH_BYTES)
    before = min(max(args.before, 0), 2)
    after = min(max(args.after, 0), 2)

    snippets: list[dict[str, Any]] = []
    scanned_files = 0
    scanned_bytes = 0
    match_lines = 0
    skipped_large: list[str] = []
    index = offset
    next_line_offset = line_offset
    stopped_for_match_limit = False
    budget_stopped = False

    while index < len(entries) and scanned_files < max_files:
        entry = entries[index]
        if entry["size"] > MAX_SEARCH_FILE_BYTES or entry["size"] > max_bytes:
            skipped_large.append(entry["path"])
            scanned_files += 1
            index += 1
            next_line_offset = 0
            continue
        if scanned_bytes + entry["size"] > max_bytes:
            budget_stopped = True
            break
        try:
            path = safe_file(root, entry["path"])
            if path.stat().st_size > min(MAX_SEARCH_FILE_BYTES, max_bytes - scanned_bytes):
                if scanned_bytes:
                    budget_stopped = True
                    break
                skipped_large.append(entry["path"])
                scanned_files += 1
                index += 1
                next_line_offset = 0
                continue
            with path.open("rb") as handle:
                raw = handle.read(min(MAX_SEARCH_FILE_BYTES, max_bytes - scanned_bytes) + 1)
            if len(raw) > min(MAX_SEARCH_FILE_BYTES, max_bytes - scanned_bytes):
                budget_stopped = True
                break
        except (OSError, ValueError):
            skipped_large.append(entry["path"])
            scanned_files += 1
            index += 1
            next_line_offset = 0
            continue
        scanned_files += 1
        scanned_bytes += len(raw)
        if b"\0" in raw[:4096]:
            skipped_large.append(entry["path"])
            index += 1
            next_line_offset = 0
            continue
        lines = raw.decode("utf-8", errors="replace").splitlines()
        for line_index in range(next_line_offset, len(lines)):
            line = lines[line_index]
            found = list(matcher.finditer(line))
            if not found:
                continue
            match_lines += 1
            if len(snippets) < MAX_SNIPPETS:
                start = max(0, line_index - before)
                end = min(len(lines), line_index + after + 1)
                snippets.append({
                    "path": entry["path"],
                    "line": line_index + 1,
                    "matches_on_line": len(found),
                    "context": [
                        {"line": i + 1, "text": redact_text(lines[i][:MAX_LINE_CHARS])}
                        for i in range(start, end)
                    ],
                })
            if match_lines >= max_matches:
                stopped_for_match_limit = True
                next_line_offset = line_index + 1
                if next_line_offset >= len(lines):
                    index += 1
                    next_line_offset = 0
                break
        if stopped_for_match_limit:
            break
        index += 1
        next_line_offset = 0

    complete = (
        index >= len(entries)
        and not skipped_large
        and not manifest["inventory"]["truncated"]
        and not stopped_for_match_limit
    )
    result = {
        "pattern": redact_text(args.pattern),
        "glob": normalize_relative_path(args.glob) if args.glob else None,
        "files_scanned": scanned_files,
        "bytes_scanned": scanned_bytes,
        "match_lines_found": match_lines,
        "snippets": snippets,
        "complete": complete,
        "next_offset": index,
        "next_line_offset": next_line_offset,
        "cursor": {"file_offset": index, "line_offset": next_line_offset},
        "remaining_files": max(0, len(entries) - index),
        "skipped_files": skipped_large[:20],
        "stopped_on_budget": budget_stopped,
    }
    while len(json_text(result).encode("utf-8")) > MAX_SEARCH_OUTPUT and result["snippets"]:
        result["snippets"].pop()
    emit(result, MAX_SEARCH_OUTPUT)
    save_session(session_dir, session)


def read_command(args: argparse.Namespace) -> None:
    root = Path(args.repo).expanduser().resolve(strict=True)
    session_dir, session, manifest = load_session(root, args.session, args.state_dir)
    entry_map = {item["path"]: item for item in manifest["inventory"]["entries"]}
    rel = normalize_relative_path(args.path)
    if rel not in entry_map or not entry_map[rel]["text_candidate"] or entry_map[rel]["excluded_reason"]:
        raise ValueError("File is not an eligible text source in this session manifest.")
    path = safe_file(root, rel)
    max_output = min(max(args.max_bytes, 1), MAX_READ_OUTPUT)
    start_line = args.start_line
    end_line = args.end_line
    if (start_line is None) != (end_line is None):
        raise ValueError("Specify both --start-line and --end-line, or neither.")
    if start_line is not None and (start_line < 1 or end_line < start_line):
        raise ValueError("Invalid line range.")

    if start_line is None:
        with path.open("rb") as handle:
            raw = handle.read(max_output + 1)
        truncated = len(raw) > max_output or path.stat().st_size > max_output
        raw = raw[:max_output]
        text = redact_text(raw.decode("utf-8", errors="replace"))
        first_line = 1
    else:
        collected: list[str] = []
        output_bytes = 0
        scanned_bytes = 0
        truncated = False
        first_line = start_line
        with path.open("rb") as handle:
            number = 0
            while True:
                raw_line = handle.readline(MAX_SOURCE_LINE_BYTES + 1)
                if not raw_line:
                    break
                number += 1
                scanned_bytes += len(raw_line)
                if scanned_bytes > MAX_READ_SCAN:
                    truncated = True
                    break
                if len(raw_line) > MAX_SOURCE_LINE_BYTES and not raw_line.endswith(b"\n"):
                    truncated = True  # Never allocate an unbounded source line.
                    break
                if number > end_line:
                    break
                if number < start_line:
                    continue
                decoded = raw_line.decode("utf-8", errors="replace")
                if len(decoded) > MAX_LINE_CHARS:
                    decoded = decoded[:MAX_LINE_CHARS] + " …[line truncated]"
                    truncated = True
                encoded_size = len(decoded.encode("utf-8"))
                if output_bytes + encoded_size > max_output:
                    truncated = True
                    break
                collected.append(decoded)
                output_bytes += encoded_size
        text = redact_text("".join(collected))

    result = {
        "path": rel,
        "start_line": first_line,
        "end_line": end_line if end_line is not None else None,
        "content": text,
        "truncated": truncated,
    }
    while len(json_text(result).encode("utf-8")) > MAX_READ_OUTPUT and result["content"]:
        result["content"] = result["content"][: int(len(result["content"]) * 0.8)]
        result["truncated"] = True
    emit(result, MAX_READ_OUTPUT)
    save_session(session_dir, session)


def count_command(args: argparse.Namespace) -> None:
    root = Path(args.repo).expanduser().resolve(strict=True)
    session_dir, session, manifest = load_session(root, args.session, args.state_dir)
    normalized_glob = normalize_relative_path(args.glob) if args.glob else None
    entries = manifest_entries(manifest, normalized_glob)

    # An inventory is only a snapshot. Ensure added/deleted files are never silently
    # omitted from a supposedly complete count, and use current per-file sizes.
    git, tracked = git_metadata(root)
    current_inventory = build_inventory(root, git, tracked, MAX_INVENTORY_ENTRIES)
    current_entries = manifest_entries({"inventory": current_inventory}, normalized_glob)
    if (
        [item["path"] for item in entries] != [item["path"] for item in current_entries]
        or (current_inventory["truncated"] and not manifest["inventory"]["truncated"])
    ):
        raise ValueError(
            "Repository file scope changed since inventory. Run inventory again "
            "before counting; prior cached results must not be reused."
        )
    live_by_path = {item["path"]: item for item in current_entries}

    flags = 0 if args.case_sensitive else re.IGNORECASE
    expression = args.pattern if args.regex else re.escape(args.pattern)
    try:
        matcher = re.compile(expression, flags)
    except re.error as exc:
        raise ValueError(f"Invalid count expression: {exc}") from exc

    job_identity = json.dumps({
        "pattern": args.pattern, "regex": args.regex,
        "case_sensitive": args.case_sensitive, "glob": normalized_glob,
    }, sort_keys=True)
    job_key = hashlib.sha256(job_identity.encode("utf-8")).hexdigest()[:12]
    # A complete or partial count is reusable only while every already scanned
    # source has the exact same SHA-256. Hash validation also detects same-size edits.
    previous_job = session["count_jobs"].get(job_key)
    invalidated_cache = False
    if previous_job and not args.restart:
        fingerprints = previous_job.get("source_fingerprints")
        if fingerprints is None:
            invalidated_cache = True  # Legacy job without content validation.
        else:
            for rel, expected in fingerprints.items():
                try:
                    if hash_file(safe_file(root, rel)) != expected:
                        invalidated_cache = True
                        break
                except (OSError, ValueError):
                    invalidated_cache = True
                    break

    if args.restart or invalidated_cache or job_key not in session["count_jobs"]:
        session["count_jobs"][job_key] = {
            "pattern": redact_text(args.pattern),
            "glob": normalized_glob,
            "regex": args.regex,
            "case_sensitive": args.case_sensitive,
            "next_offset": 0,
            "files_scanned": 0,
            "files_matched": 0,
            "matches": 0,
            "bytes_scanned": 0,
            "skipped_large_files": [],
            "source_fingerprints": {},
            "finished": False,
            "complete": False,
        }
    job = session["count_jobs"][job_key]
    if job.get("finished") or job["complete"]:
        emit({"job_id": job_key, "invalidated_cache": invalidated_cache, **job})
        return

    max_files = min(max(args.max_files, 1), MAX_COUNT_FILES)
    max_bytes = min(max(args.max_bytes, 1), MAX_COUNT_BYTES)
    batch_files = 0
    batch_bytes = 0
    index = job["next_offset"]
    while index < len(entries) and batch_files < max_files:
        entry = entries[index]
        size = live_by_path[entry["path"]]["size"]
        if size > MAX_COUNT_FILE_BYTES:
            skipped = job["skipped_large_files"]
            if len(skipped) < 20:
                skipped.append(entry["path"])
            batch_files += 1
            index += 1
            continue
        if size > max_bytes:
            skipped = job["skipped_large_files"]
            if len(skipped) < 20:
                skipped.append(entry["path"])
            batch_files += 1
            index += 1
            continue
        if batch_bytes + size > max_bytes:
            break
        try:
            path = safe_file(root, entry["path"])
            file_matches = 0
            fingerprint = hashlib.sha256()
            with path.open("rb") as handle:
                while True:
                    raw_line = handle.readline(MAX_SOURCE_LINE_BYTES + 1)
                    if not raw_line:
                        break
                    if len(raw_line) > MAX_SOURCE_LINE_BYTES and not raw_line.endswith(b"\n"):
                        raise ValueError("File contains a source line over the count limit.")
                    fingerprint.update(raw_line)
                    file_matches += sum(
                        1 for _ in matcher.finditer(raw_line.decode("utf-8", errors="replace"))
                    )
        except (OSError, ValueError):
            skipped = job["skipped_large_files"]
            if len(skipped) < 20:
                skipped.append(entry["path"])
            batch_files += 1
            index += 1
            continue
        job["files_scanned"] += 1
        job["source_fingerprints"][entry["path"]] = fingerprint.hexdigest()
        if file_matches:
            job["files_matched"] += 1
        job["matches"] += file_matches
        job["bytes_scanned"] += size
        batch_bytes += size
        batch_files += 1
        index += 1

    job["next_offset"] = index
    job["finished"] = index >= len(entries)
    job["complete"] = (
        job["finished"]
        and not job["skipped_large_files"]
        and not manifest["inventory"]["truncated"]
        and not current_inventory["truncated"]
    )
    job["incomplete_reason"] = None
    if job["skipped_large_files"]:
        job["incomplete_reason"] = "One or more files were skipped because they exceeded the per-file limit or could not be read."
    elif manifest["inventory"]["truncated"] or current_inventory["truncated"]:
        job["incomplete_reason"] = "The source manifest was truncated."
    elif not job["complete"]:
        job["incomplete_reason"] = "More bounded batches remain."

    save_session(session_dir, session)
    emit({
        "job_id": job_key,
        "pattern": redact_text(args.pattern),
        "glob": normalized_glob,
        "invalidated_cache": invalidated_cache,
        "files_scanned": job["files_scanned"],
        "files_matched": job["files_matched"],
        "matches": job["matches"],
        "bytes_scanned": job["bytes_scanned"],
        "skipped_large_files": job["skipped_large_files"],
        "complete": job["complete"],
        "next_offset": job["next_offset"],
        "remaining_files": max(0, len(entries) - index),
        "incomplete_reason": job["incomplete_reason"],
    })


def evidence_add_command(args: argparse.Namespace) -> None:
    root = Path(args.repo).expanduser().resolve(strict=True)
    session_dir, session, manifest = load_session(root, args.session, args.state_dir)
    entry_map = {item["path"]: item for item in manifest["inventory"]["entries"]}
    rel = normalize_relative_path(args.path)
    if rel not in entry_map or not entry_map[rel]["text_candidate"] or entry_map[rel]["excluded_reason"]:
        raise ValueError("Evidence source must be an eligible file in the session manifest.")
    path = safe_file(root, rel)
    if args.start_line is not None and args.start_line < 1:
        raise ValueError("Line numbers start at 1.")
    if args.end_line is not None and (args.start_line is None or args.end_line < args.start_line):
        raise ValueError("end-line requires a valid start-line.")
    claim = args.claim.strip()
    if not claim or len(claim) > 1200:
        raise ValueError("Claim must contain 1 to 1,200 characters.")
    record = {
        "id": uuid.uuid4().hex[:16],
        "claim": redact_text(claim),
        "classification": args.classification,
        "scope": redact_text((args.scope or "").strip()[:500]),
        "sources": [{
            "path": rel,
            "sha256": hash_file(path),
            "symbol": redact_text((args.symbol or "").strip()[:300]) or None,
            "start_line": args.start_line,
            "end_line": args.end_line,
        }],
        "notes": redact_text((args.notes or "").strip()[:1000]),
        "created_at": now_iso(),
        "reused_from_session_id": None,
    }
    append_jsonl(session_dir / "evidence.jsonl", record)
    save_session(session_dir, session)
    emit({
        "stored": True,
        "evidence_id": record["id"],
        "classification": record["classification"],
        "source": rel,
        "source_sha256": record["sources"][0]["sha256"],
    })


def checkpoint_command(args: argparse.Namespace) -> None:
    root = Path(args.repo).expanduser().resolve(strict=True)
    session_dir, session, _ = load_session(root, args.session, args.state_dir)
    session["phase"] = args.phase
    completed = args.completed_task
    if completed:
        tasks = session["checkpoint"]["completed_tasks"]
        if completed not in tasks and len(tasks) < 200:
            tasks.append(completed)
    if args.next_task is not None:
        session["checkpoint"]["next_task"] = args.next_task
    if args.phase == "done":
        session["status"] = "completed"
    elif args.phase == "approval":
        session["status"] = "needs_approval"
    else:
        session["status"] = "active"
    save_session(session_dir, session)
    emit({
        "session_id": session["session_id"],
        "phase": session["phase"],
        "status": session["status"],
        "completed_tasks": session["checkpoint"]["completed_tasks"],
        "next_task": session["checkpoint"]["next_task"],
    })


